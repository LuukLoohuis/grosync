export const productIcoon = (naam: string): string => {
  const kaal = countParts(naam).rest.toLocaleLowerCase('nl');
  return PRODUCTEN.find(([patroon]) => patroon.test(kaal))?.[1] ?? PER_AFDELING[departmentOf(kaal)];
};
